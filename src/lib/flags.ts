/** flagcdn.com (flagpedia CDN) country code, or null if unknown. */
export function flagCode(name: string): string | null {
  if (name === "England") return "gb-eng";
  if (name === "Scotland") return "gb-sct";
  const iso = ISO[name];
  return iso ? iso.toLowerCase() : null;
}
